"""The call_indirect dispatch of ffi_call_js for mixed signatures, as C: python3 tools/gen_ffi.py > ffi_calls.h

WebAssembly calls a function through the table with the exact type, so every combination is its own case: up to 4
arguments of the classes i32 (integers and pointers), i64, f32, f64 (4**0 + ... + 4**4 = 341 patterns) and a result
of void, i32, i64, f32 or f64: 1705 cases. The selector is `pattern * 5 + result`, the pattern being the base-4 digits
of the argument classes preceded by their count (offsets 0, 1, 5, 21, 85). Generated at build time, not committed.
"""

import itertools

CLASSES = ("i", "l", "f", "d")  # members of the Arg union: i32, i64, f32, f64
CT = {"i": "u32", "l": "u64", "f": "float", "d": "double"}
RET = (("void", None), ("u32", "i"), ("u64", "l"), ("float", "f"), ("double", "d"))
OFFSET = (0, 1, 5, 21, 85)

print("// generated by tools/gen_ffi.py: do not edit")
print("typedef union { u32 i; u64 l; float f; double d; } Arg;")
print("static void ffi_dispatch(u32 fn, u32 sel, const Arg *a, Arg *r) {")
print("    switch (sel) {")
for n in range(5):
    for combo in itertools.product(range(4), repeat=n):
        value = 0
        for c in combo:
            value = value * 4 + c
        pid = OFFSET[n] + value
        params = ", ".join(CT[CLASSES[c]] for c in combo) or "void"
        args = ", ".join(f"a[{k}].{CLASSES[c]}" for k, c in enumerate(combo))
        for rc, (rt, member) in enumerate(RET):
            call = f"(({rt} (*)({params}))fn)({args})"
            body = f"{call};" if member is None else f"r->{member} = {call};"
            print(f"        case {pid * 5 + rc}: {body} break;")
print("        default: __builtin_trap();")
print("    }")
print("}")
